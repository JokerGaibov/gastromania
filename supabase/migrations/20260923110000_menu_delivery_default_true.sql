-- Меняем дефолт available_for_delivery с false на true.
--
-- Причина: подавляющее большинство блюд ресторан возит, а исключения
-- (банкетные позиции, то что не переживает доставку) — редкость. Заводить
-- каждое новое блюдо и не забывать включать галочку оказалось неудобно:
-- блюдо молча не появлялось в доставке. Теперь наоборот — недоставочные
-- позиции админ выключает вручную.
--
-- ВАЖНО: alter column ... set default меняет значение только для БУДУЩИХ
-- вставок. Существующие строки Postgres не переписывает — у блюд, где
-- сейчас false, false и останется, в том числе у тех, кому его проставили
-- вручную после 20260923100000. Массового update здесь намеренно нет.
--
-- Идемпотентна: повторный set default выставляет то же самое значение.
alter table public.menu_items alter column available_for_delivery set default true;
